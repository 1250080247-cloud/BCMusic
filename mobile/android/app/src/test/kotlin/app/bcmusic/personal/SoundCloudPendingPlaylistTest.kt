package app.bcmusic.personal

import android.app.Application
import android.content.Context
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import kotlin.math.abs

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], application = Application::class)
class SoundCloudPendingPlaylistTest {
    private val context: Context get() = RuntimeEnvironment.getApplication()

    @Before
    fun setUp() {
        context.getSharedPreferences("bcmusic-pending-playlists", Context.MODE_PRIVATE).edit().clear().commit()
        context.getSharedPreferences("bcmusic-playlists", Context.MODE_PRIVATE).edit().clear().commit()
    }

    @Test
    fun canonicalTrackIdMatchesDownloadAndReconcilesToPlaylist() {
        val pendingStore = PendingPlaylistStore(context)
        val playlistStore = PlaylistStore(context).apply { load() }

        // User creates playlist
        val playlist = playlistStore.create("SoundCloud Chill", null)

        // Canonical ID from SoundCloud resolver is soundcloud_<numeric_id>
        val canonicalId = "soundcloud_987654321"

        // Enqueue registers pending with canonicalId
        pendingStore.add(canonicalId, playlist.id)
        assertTrue(pendingStore.has(canonicalId, playlist.id))

        // When download finishes, simulate reconcile logic with canonicalId
        val targetPlaylists = pendingStore.getPlaylistsForTrack(canonicalId)
        assertEquals(listOf(playlist.id), targetPlaylists)

        for (pId in targetPlaylists) {
            playlistStore.add(pId, canonicalId)
            pendingStore.remove(canonicalId, pId)
        }

        // Verify track is in playlist and pending is cleared
        val updatedPlaylist = playlistStore.items.first { it.id == playlist.id }
        assertTrue(updatedPlaylist.trackIds.contains(canonicalId))
        assertFalse(pendingStore.has(canonicalId, playlist.id))
    }

    @Test
    fun legacyHashIdIsReconciledWhenDownloadCompletes() {
        val pendingStore = PendingPlaylistStore(context)
        val playlistStore = PlaylistStore(context).apply { load() }

        val playlist = playlistStore.create("Legacy Playlist", null)

        val soundCloudUrl = "https://soundcloud.com/artist/track-slug"
        val canonicalId = "soundcloud_555444333"
        // Legacy hash ID previously generated by Flutter
        val legacyHashId = "soundcloud_${abs(soundCloudUrl.hashCode())}"

        // Suppose legacy pending store had the hash ID
        pendingStore.add(legacyHashId, playlist.id)
        assertTrue(pendingStore.has(legacyHashId, playlist.id))

        // When canonicalId download finishes, check if sourceUrl matches legacyHashId
        val targetPlaylists = pendingStore.getPlaylistsForTrack(canonicalId).toMutableSet()
        val computedLegacyId = "soundcloud_${abs(soundCloudUrl.hashCode())}"
        val legacyTargets = pendingStore.getPlaylistsForTrack(computedLegacyId)
        for (pId in legacyTargets) {
            targetPlaylists.add(pId)
            pendingStore.remove(computedLegacyId, pId)
        }

        assertEquals(setOf(playlist.id), targetPlaylists)
        for (pId in targetPlaylists) {
            playlistStore.add(pId, canonicalId)
        }

        // Verify playlist has the canonical ID and legacy pending is cleaned up
        val updatedPlaylist = playlistStore.items.first { it.id == playlist.id }
        assertTrue(updatedPlaylist.trackIds.contains(canonicalId))
        assertFalse(pendingStore.has(legacyHashId, playlist.id))
    }
}
